//! In-game Valorant chat text expander.
//!
//! The Riot chat HTTP API only sees messages **our overlay** sends. When the
//! player types in the native game chat box, nothing hits our code — so
//! shortcuts would never fire. This module installs a Windows low-level
//! keyboard hook that, while VALORANT is focused and the chat bar is open:
//!   - buffers what is typed
//!   - on Enter (send), expands `sa` / `as` / `<3` / `!t <lang> …` before send
//!
//! Expansion: swallow Enter (down **and** matching up) → Ctrl+A / Ctrl+C the
//! real chat line (the hook buffer is ASCII-only — `ToUnicode` times out the
//! hook, so TR letters never land in it) → transform → clear line → paste
//! expanded text via clipboard (Unicode SendInput was dropping mid-string in
//! Valorant) → Enter. Translate (`!t`) runs on a background thread so the
//! hook never blocks.
//!
//! Valorant keeps the chat bar **open after send** until Escape — so we must
//! keep `chat_open = true` after a send, otherwise the next line is not
//! buffered and shortcuts randomly "stop working".
//!
//! # Reliability notes
//!
//! - Swallowing only Enter **keydown** left the real **keyup** free to reach
//!   Valorant; the game sometimes treated that as a send of the short form
//!   (`sa`) before our inject thread finished. Both edges are suppressed for
//!   the expansion window.
//! - `Focus::Unknown` (foreground poller lag) used to drop keystrokes entirely,
//!   so short messages like `sa` intermittently never buffered. While the chat
//!   bar is already open we keep buffering through Unknown / IME / overlays.
//! - Paste + send pacing is intentionally slower than a human mash — Valorant
//!   drops clipboard paste / mid-string input when the inject is too tight.
//! - A short idle timeout used to treat "chat left open between rounds" as
//!   closed. The next `sa` was not buffered and went out raw. Held gameplay
//!   keys (WASD auto-repeat) are the signal that chat actually closed.
//!
//! # Staying alive
//!
//! Windows enforces `LowLevelHooksTimeout` (~300 ms by default) on
//! `WH_KEYBOARD_LL` callbacks. On Windows 7+ a hook that overruns it is
//! **silently removed** — no error, no callback, ever again. That is why the
//! shortcuts used to die mid-session and only came back after an app restart.
//! Guards:
//!   1. The hook body is cheap: no `OpenProcess`, no `ToUnicode` / IME, no
//!      rule-table clones. A ~80 ms background poller resolves focus instead.
//!   2. A watchdog compares physical key transitions (`GetAsyncKeyState`)
//!      against hook heartbeats. SendInput probes are not used — Vanguard
//!      often starts blocking synthetic keys mid-session, which made the
//!      old probe look dead and reset chat state every few seconds.
//!   3. Recovery recycles the **whole hook thread**. Reinstalling on the
//!      same thread after a silent unhook frequently never fires again.

