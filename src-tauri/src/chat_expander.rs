/// LLKHF_INJECTED — key was generated by SendInput / another process.
const LLKHF_INJECTED: u32 = 0x10;

/// How long the chat bar may sit untouched before we assume the game closed it.
/// Valorant leaves the bar open after send, so this must be longer than a
/// typical round gap — otherwise the next `sa` is typed against a "closed"
/// buffer and goes out raw. Held gameplay keys (auto-repeat) close it sooner.
const CHAT_IDLE_TIMEOUT_MS: u64 = 180_000;

/// Alt-tab / IME / overlay flicker: don't drop `chat_open` on a brief
/// non-Valorant foreground blip.
const FOCUS_OTHER_GRACE_MS: u64 = 400;

/// Foreground classification published by the poller (hook only reads this).
const FG_OTHER: u32 = 0;
const FG_VALORANT: u32 = 1;
/// IME / overlay / unreadable process — do not reset chat state.
const FG_NEUTRAL: u32 = 2;

/// After we swallow Enter-down for an expansion, suppress real Enter events
/// (especially keyup) until this many ms have elapsed. Prevents Valorant from
/// sending the unexpanded short form on the orphaned keyup.
